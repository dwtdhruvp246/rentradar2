import { supabase } from "./supabaseClient.js";

export async function downloadPaymentReceipt(payment) {
  const { jsPDF } = await import("https://cdn.jsdelivr.net/npm/jspdf@2.5.2/+esm");
  const ids = [payment.tenant_id, payment.landlord_id].filter(Boolean);
  const { data: profiles } = ids.length ? await supabase.from("profiles").select("id,full_name").in("id", ids) : { data: [] };
  const names = Object.fromEntries((profiles || []).map((profile) => [profile.id, profile.full_name]));
  const pdf = new jsPDF({ unit: "mm", format: "a4" });
  pdf.setFillColor(23, 61, 58); pdf.rect(0, 0, 210, 38, "F");
  pdf.setTextColor(255, 255, 255); pdf.setFont("helvetica", "bold"); pdf.setFontSize(22); pdf.text("MUSHAVO", 18, 20);
  pdf.setFont("helvetica", "normal"); pdf.setFontSize(9); pdf.text("Your property, handled simply.", 18, 28);
  pdf.setTextColor(23, 38, 45); pdf.setFont("helvetica", "bold"); pdf.setFontSize(18); pdf.text("Payment receipt", 18, 56);
  pdf.setFontSize(9); pdf.setTextColor(93, 107, 114); pdf.text(`Receipt ID: ${payment.id}`, 18, 64);
  const rows = [
    ["Payer", names[payment.tenant_id] || payment.tenant_id || "Not recorded"],
    ["Payee", names[payment.landlord_id] || payment.landlord_id || "Not recorded"],
    ["Purpose", title(payment.payment_type)],
    ["Amount", `${payment.currency} ${Number(payment.amount).toFixed(2)}`],
    ["Paid on", new Date(payment.paid_at).toLocaleString()],
    ["Rental period", payment.rental_period_start ? `${payment.rental_period_start} to ${payment.rental_period_end || "open"}` : "Not applicable"],
    ["Reference", payment.reference || "Not provided"],
    ["Notes", payment.notes || "None"],
  ];
  let y = 78; rows.forEach(([label, value]) => { pdf.setFont("helvetica", "bold"); pdf.setTextColor(93, 107, 114); pdf.text(label, 18, y); pdf.setFont("helvetica", "normal"); pdf.setTextColor(23, 38, 45); const lines = pdf.splitTextToSize(String(value), 125); pdf.text(lines, 62, y); y += Math.max(10, lines.length * 5 + 4); });
  pdf.setDrawColor(217, 227, 227); pdf.line(18, y + 2, 192, y + 2); pdf.setFontSize(8); pdf.setTextColor(93, 107, 114); pdf.text("Generated by Mushavo. Verify this record against the account payment history.", 18, y + 12);
  pdf.save(`mushavo-receipt-${payment.id.slice(0, 8)}.pdf`);
}

function title(value) { return String(value || "payment").replaceAll("_", " ").replace(/\b\w/g, (letter) => letter.toUpperCase()); }
